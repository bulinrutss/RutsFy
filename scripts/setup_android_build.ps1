# JDK 17 (winget) + Android SDK in repo .android-sdk/
# Usage: powershell -ExecutionPolicy Bypass -File scripts/setup_android_build.ps1

$ErrorActionPreference = "Stop"
$RepoRoot = Split-Path $PSScriptRoot -Parent
$SdkRoot = Join-Path $RepoRoot ".android-sdk"
$LocalProps = Join-Path $RepoRoot "android\local.properties"

function Find-JavaHome {
    if ($env:JAVA_HOME) {
        $jh = $env:JAVA_HOME.Trim()
        if ($jh -and (Test-Path (Join-Path $jh "bin\java.exe"))) {
            return $jh
        }
    }
    $candidates = @(
        "${env:ProgramFiles}\Microsoft\jdk-17*",
        "${env:ProgramFiles}\Android\Android Studio\jbr",
        "${env:ProgramFiles}\Eclipse Adoptium\jdk-17*",
        "${env:ProgramFiles}\Java\jdk-17*"
    )
    foreach ($pattern in $candidates) {
        $hit = Get-Item $pattern -ErrorAction SilentlyContinue | Sort-Object FullName -Descending | Select-Object -First 1
        if ($hit -and (Test-Path (Join-Path $hit.FullName "bin\java.exe"))) {
            return $hit.FullName
        }
    }
    $java = Get-Command java -ErrorAction SilentlyContinue
    if ($java) {
        $bin = Split-Path $java.Source -Parent
        return (Resolve-Path (Join-Path $bin "..")).Path
    }
    return $null
}

function Ensure-Jdk17 {
    $javaHome = Find-JavaHome
    if ($javaHome) {
        Write-Host "[jdk] OK: $javaHome"
        return $javaHome
    }
    Write-Host "[jdk] Installing Microsoft OpenJDK 17 (winget)..."
    winget install --id Microsoft.OpenJDK.17 -e --accept-source-agreements --accept-package-agreements
    $javaHome = Find-JavaHome
    if (-not $javaHome) {
        throw "JDK 17 not found after winget. Restart terminal or set JAVA_HOME."
    }
    Write-Host "[jdk] OK: $javaHome"
    return $javaHome
}

function Ensure-AndroidSdk {
    New-Item -ItemType Directory -Force -Path $SdkRoot | Out-Null
    $cliLatest = Join-Path $SdkRoot "cmdline-tools\latest"
    $sdkmanager = Join-Path $cliLatest "bin\sdkmanager.bat"
    if (-not (Test-Path $sdkmanager)) {
        Write-Host "[sdk] Downloading Android command-line tools..."
        $zip = Join-Path $env:TEMP "android-cmdline-tools.zip"
        $url = "https://dl.google.com/android/repository/commandlinetools-win-11076708_latest.zip"
        Invoke-WebRequest -Uri $url -OutFile $zip -UseBasicParsing
        $extract = Join-Path $env:TEMP "android-cmdline-tools"
        if (Test-Path $extract) { Remove-Item $extract -Recurse -Force }
        Expand-Archive -Path $zip -DestinationPath $extract -Force
        New-Item -ItemType Directory -Force -Path (Join-Path $SdkRoot "cmdline-tools") | Out-Null
        if (Test-Path $cliLatest) { Remove-Item $cliLatest -Recurse -Force }
        Move-Item (Join-Path $extract "cmdline-tools") $cliLatest
        Remove-Item $zip -Force -ErrorAction SilentlyContinue
    }
    Write-Host "[sdk] Licenses + packages (sdkmanager via Python)..."
    $jh = Ensure-Jdk17
    $py = @"
import subprocess, os
sm = r'$sdkmanager'
sdk = r'$SdkRoot'
java = r'$jh'
env = os.environ.copy()
env['JAVA_HOME'] = java
env['PATH'] = os.path.join(java, 'bin') + os.pathsep + env.get('PATH', '')
yes = b'y\n' * 120
for args in [['--licenses'], ['platform-tools', 'platforms;android-35', 'build-tools;35.0.0', 'build-tools;34.0.0']]:
    subprocess.run([sm, f'--sdk_root={sdk}'] + args, input=yes, env=env, check=True)
"@
    python -c $py
    if ($LASTEXITCODE -ne 0) {
        throw "sdkmanager falhou (exit $LASTEXITCODE)"
    }
    Write-Host "[sdk] OK: $SdkRoot"
}

function Write-LocalProperties {
    $sdkDir = $SdkRoot -replace "\\", "/"
    @(
        "## Generated by scripts/setup_android_build.ps1 (do not commit).",
        "sdk.dir=$sdkDir"
    ) | Set-Content -Path $LocalProps -Encoding UTF8
    Write-Host "[gradle] local.properties -> $LocalProps"
}

$javaHome = Ensure-Jdk17
$env:JAVA_HOME = $javaHome
$env:PATH = "$javaHome\bin;$env:PATH"
Ensure-AndroidSdk
Write-LocalProperties
Write-Host ""
Write-Host "[ok] Android build ready. Run: python scripts/build_android_apk.py"
